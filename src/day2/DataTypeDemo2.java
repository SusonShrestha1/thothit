package day2;

public class DataTypeDemo2 {

	public static void main(String[] args) {

		float num1 = 20.3F;
		float num2 = 30.4f;
		float result = num1 + num2;
		
		System.out.println(result);
		
		double radius = 22.2;
		
		double area = Math.PI * radius * radius;
		System.out.println("The value of the area is " + area);
	}

}
