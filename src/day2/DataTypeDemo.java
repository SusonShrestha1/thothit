package day2;

public class DataTypeDemo {

	public static void main(String[] args) {
		
		System.out.println("we are learning datatype");
		
		int num1 = 100;
		System.out.println(num1);
		System.out.println("The value of number 1 is " + num1);
		
		num1 = 200;
		System.out.println(num1);
		System.out.println("The value of number 1 is " + num1);
		
		
		float percentage = 70.8F;
		double score = 20.4;
		char sex = 'M';
		String myName = "Suson";
		
		System.out.println("My name is " + myName + " and I am a male "+ sex + ". I got the score of " + score + " and percentage " + percentage + ".");
	}

}
